"""Business documents from voice: bill, quotation, purchase order, statement.

Templates are HTML with {{placeholders}}. The owner can upload their own format (photo/PDF);
Sarvam Document AI reads it and its header text becomes the template header. PDFs are rendered
with a local headless Edge/Chrome (correct shaping for Kannada/Devanagari), falling back to HTML.
"""
import datetime as dt
import html
import os
import shutil
import subprocess
import uuid
from pathlib import Path
from tempfile import TemporaryDirectory

from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

import config
import db

BASE_CSS = """body{font-family:'Noto Sans','Nirmala UI',Arial,sans-serif;margin:32px;color:#1d1d1f}
h1{font-size:22px;margin:0}.muted{color:#666;font-size:12px}table{width:100%;border-collapse:collapse;margin-top:16px}
th,td{border-bottom:1px solid #ddd;padding:8px;text-align:left;font-size:13px}th{background:#f4f4f6}
.r{text-align:right}.total{font-weight:700;font-size:15px}.box{border:1px solid #ddd;border-radius:8px;padding:12px;margin-top:12px}"""

DEFAULTS = {
    "bill": ("Bill", "Bill / ಬಿಲ್ / बिल"),
    "quotation": ("Quotation", "Quotation / ದರಪಟ್ಟಿ / कोटेशन"),
    "purchase_order": ("Purchase Order", "Purchase Order / ಖರೀದಿ ಆದೇಶ / ख़रीद आदेश"),
    "statement": ("Statement", "Account Statement / ಖಾತೆ ವಿವರ / खाता विवरण"),
}


def default_html(kind: str) -> str:
    _, title = DEFAULTS.get(kind, DEFAULTS["bill"])
    return f"""<html><head><meta charset="utf-8"><style>{BASE_CSS}</style></head><body>
<h1>{{{{shop_name}}}}</h1><div class="muted">{{{{shop_header}}}}</div>
<h2 style="font-size:16px;margin-top:20px">{title}</h2>
<div class="box">To: <b>{{{{to_name}}}}</b><br>Date: {{{{date}}}}<br>No: {{{{doc_no}}}}</div>
{{{{items_table}}}}
<p class="total">Total: ₹ {{{{total}}}}</p><p>{{{{note}}}}</p>
<p class="muted">Generated by Bolo from a voice note · {{{{date}}}}</p></body></html>"""


def seed_templates() -> None:
    for kind in DEFAULTS:
        db.run("INSERT OR IGNORE INTO templates(name, kind, html, source, created_at) VALUES (?,?,?,?,?)",
               (kind, kind, default_html(kind), "default", db.now()))


def items_table(items: list[dict]) -> tuple[str, float]:
    rows, total = [], 0.0
    for it in items:
        qty = float(it.get("qty") or 1)
        rate = float(it.get("rate") or it.get("price") or 0)
        amt = float(it.get("amount") or qty * rate)
        total += amt
        rows.append(f"<tr><td>{html.escape(str(it.get('name', '')))}</td><td class='r'>{qty:g}</td>"
                    f"<td class='r'>{rate:g}</td><td class='r'>{amt:,.2f}</td></tr>")
    table = ("<table><tr><th>Item</th><th class='r'>Qty</th><th class='r'>Rate</th><th class='r'>Amount</th></tr>"
             + "".join(rows) + "</table>") if rows else ""
    return table, round(total, 2)


def render(kind: str, fields: dict) -> str:
    t = db.q1("SELECT html FROM templates WHERE name=?", (kind,)) or {"html": default_html(kind)}
    table, total = items_table(fields.get("items") or [])
    values = {
        "shop_name": db.setting("shop_name"), "shop_header": db.setting("shop_header") if db.setting("shop_header") else "",
        "to_name": fields.get("to_name", ""), "date": dt.date.today().strftime("%d %b %Y"),
        "doc_no": fields.get("doc_no", uuid.uuid4().hex[:6].upper()), "items_table": fields.get("items_html") or table,
        "total": f"{float(fields.get('total') or total):,.2f}", "note": html.escape(fields.get("note", "")),
    }
    out = t["html"]
    for k, v in values.items():
        out = out.replace("{{" + k + "}}", str(v))
    return out


def _browser() -> str | None:
    for p in (shutil.which("msedge"), shutil.which("chrome"),
              r"C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe",
              r"C:\Program Files\Microsoft\Edge\Application\msedge.exe",
              r"C:\Program Files\Google\Chrome\Application\chrome.exe",
              "/usr/bin/chromium", "/usr/bin/google-chrome"):
        if p and os.path.exists(p):
            return p
    return None


def _standard_pdf(kind: str, fields: dict, path: str) -> None:
    """Compact local renderer for the standard template and Latin-script shop data."""
    styles = getSampleStyleSheet()
    story = []

    def paragraph(value, style="BodyText"):
        text = str(value).replace("₹", "Rs. ")
        story.append(Paragraph(html.escape(text), styles[style]))

    paragraph(db.setting("shop_name"), "Title")
    if db.setting("shop_header"):
        paragraph(db.setting("shop_header"))
    paragraph(DEFAULTS[kind][0], "Heading2")
    paragraph(f"To: {fields.get('to_name', '')}")
    paragraph(f"Date: {dt.date.today().isoformat()}    No: {fields['doc_no']}")
    story.append(Spacer(1, 14))
    rows = [["Item", "Qty", "Rate (Rs.)", "Amount (Rs.)"]]
    for item in fields.get("items", []):
        qty = float(item.get("qty") or 1)
        rate = float(item.get("rate") or item.get("price") or 0)
        amount = float(item.get("amount") or qty * rate)
        rows.append([Paragraph(html.escape(str(item.get("name") or "")), styles["BodyText"]),
                     f"{qty:g}", f"{rate:,.2f}", f"{amount:,.2f}"])
    if len(rows) > 1:
        table = Table(rows, colWidths=[191, 52, 78, 95], repeatRows=1, hAlign="LEFT")
        table.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#e3efe9")),
                                   ("ALIGN", (1, 1), (-1, -1), "RIGHT"),
                                   ("VALIGN", (0, 0), (-1, -1), "MIDDLE")]))
        story.append(table)
    _, total = items_table(fields.get("items", []))
    paragraph(f"Total: Rs. {total:,.2f}", "Heading3")
    paragraph(fields.get("note") or "")
    SimpleDocTemplate(path, title=DEFAULTS[kind][0]).build(story)


def to_pdf(html_text: str, stem: str) -> tuple[str, str]:
    """Return (path, mime). PDF when a browser is available, else HTML."""
    html_path = os.path.join(config.DOCS_DIR, f"{stem}.html")
    with open(html_path, "w", encoding="utf-8") as f:
        f.write(html_text)
    browser = _browser()
    if browser:
        pdf_path = os.path.join(config.DOCS_DIR, f"{stem}.pdf")
        try:
            with TemporaryDirectory(prefix="bolo-pdf-") as profile:
                subprocess.run([browser, "--headless=new", "--disable-gpu", "--no-pdf-header-footer",
                                "--disable-background-networking", f"--user-data-dir={profile}",
                                f"--print-to-pdf={pdf_path}", Path(html_path).resolve().as_uri()],
                               check=True, timeout=15, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            if os.path.exists(pdf_path) and os.path.getsize(pdf_path) > 0:
                return pdf_path, "application/pdf"
        except Exception as e:
            print("[pdf] browser render failed:", e)
    return html_path, "text/html"


def make(kind: str, fields: dict, contact_id: int | None = None) -> dict:
    stem = f"{kind}_{uuid.uuid4().hex[:8]}"
    template = db.q1("SELECT html FROM templates WHERE name=?", (kind,))
    standard = kind in DEFAULTS and (not template or template["html"] == default_html(kind))
    shop_text = str(fields) + db.setting("shop_name") + db.setting("shop_header")
    fields = {**fields, "doc_no": fields.get("doc_no") or uuid.uuid4().hex[:6].upper()}
    if standard and shop_text.replace("₹", "").isascii():
        path = os.path.join(config.DOCS_DIR, f"{stem}.pdf")
        _standard_pdf(kind, fields, path)
        mime = "application/pdf"
    else:
        path, mime = to_pdf(render(kind, fields), stem)
    did = db.run("INSERT INTO documents(template, contact_id, path, fields, status, created_at) VALUES (?,?,?,?,?,?)",
                 (kind, contact_id, path, str(fields), "draft", db.now()))
    return {"id": did, "path": path, "mime": mime, "filename": f"{DEFAULTS.get(kind, ('Doc',))[0]}{os.path.splitext(path)[1]}"}


def save_custom(kind: str, parsed_text: str) -> None:
    """Owner's own format: keep the parsed text as source and use its first lines as our header."""
    header_lines = [ln.strip("#* ").strip() for ln in parsed_text.splitlines() if ln.strip()][:3]
    if header_lines:
        db.set_setting("shop_header", " · ".join(header_lines))
    db.run("UPDATE templates SET source=? WHERE name=?", (parsed_text[:5000], kind))
